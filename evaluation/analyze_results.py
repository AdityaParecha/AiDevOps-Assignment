"""
Model Evaluation Analysis
=========================

Analyzes the results generated by evaluate.py.

Input:
    results_final.csv

Outputs:
    model_summary.csv

Metrics:
    - Number of evaluations
    - Average latency
    - Median latency
    - Average generation time
    - Average total tokens
    - Average output tokens
    - Average retrieval recall
    - Average CPU usage
    - Average memory usage
    - Blank/error responses
"""

from pathlib import Path

import pandas as pd


# ---------------------------------------------------------------------------
# Configuration
# ---------------------------------------------------------------------------

BASE_DIR = Path(__file__).resolve().parent

INPUT_FILE = BASE_DIR / "results_final.csv"
OUTPUT_FILE = BASE_DIR / "model_summary.csv"


# ---------------------------------------------------------------------------
# Load data
# ---------------------------------------------------------------------------

def load_results(file_path: Path) -> pd.DataFrame:
    """Load and validate the evaluation results CSV."""

    if not file_path.exists():
        raise FileNotFoundError(
            f"Results file not found: {file_path}"
        )

    df = pd.read_csv(file_path)

    required_columns = [
        "model",
        "question_id",
        "answer",
        "latency_ms",
        "output_tokens",
        "total_tokens",
        "generation_time_ms",
        "retrieval_recall",
        "cpu_peak_pct",
        "memory_peak_pct",
    ]

    missing_columns = [
        column for column in required_columns
        if column not in df.columns
    ]

    if missing_columns:
        raise ValueError(
            f"Missing required columns: {missing_columns}"
        )

    return df


# ---------------------------------------------------------------------------
# Data cleaning
# ---------------------------------------------------------------------------

def prepare_data(df: pd.DataFrame) -> pd.DataFrame:
    """Prepare data for analysis."""

    numeric_columns = [
        "latency_ms",
        "prompt_tokens",
        "output_tokens",
        "total_tokens",
        "generation_time_ms",
        "retrieval_recall",
        "cpu_baseline_pct",
        "cpu_peak_pct",
        "memory_baseline_pct",
        "memory_peak_pct",
    ]

    for column in numeric_columns:
        if column in df.columns:
            df[column] = pd.to_numeric(
                df[column],
                errors="coerce",
            )

    # Detect empty or missing model answers.
    df["blank_answer"] = (
        df["answer"]
        .fillna("")
        .astype(str)
        .str.strip()
        .eq("")
    )

    # Detect service errors.
    if "error" in df.columns:
        df["has_error"] = (
            df["error"]
            .fillna("")
            .astype(str)
            .str.strip()
            .ne("")
        )
    else:
        df["has_error"] = False

    return df


# ---------------------------------------------------------------------------
# Model summary
# ---------------------------------------------------------------------------

def create_model_summary(df: pd.DataFrame) -> pd.DataFrame:
    """Create model-wise performance summary."""

    summary = (
        df.groupby("model")
        .agg(
            evaluations=("question_id", "count"),

            avg_latency_ms=("latency_ms", "mean"),
            median_latency_ms=("latency_ms", "median"),

            avg_generation_time_ms=(
                "generation_time_ms",
                "mean",
            ),

            avg_output_tokens=("output_tokens", "mean"),
            avg_total_tokens=("total_tokens", "mean"),

            avg_retrieval_recall=(
                "retrieval_recall",
                "mean",
            ),

            avg_cpu_peak_pct=("cpu_peak_pct", "mean"),
            avg_memory_peak_pct=(
                "memory_peak_pct",
                "mean",
            ),

            blank_answers=("blank_answer", "sum"),
            errors=("has_error", "sum"),
        )
        .reset_index()
    )

    # Round numerical values for readability.
    numeric_columns = summary.select_dtypes(
        include="number"
    ).columns

    summary[numeric_columns] = summary[numeric_columns].round(2)

    return summary


# ---------------------------------------------------------------------------
# Print report
# ---------------------------------------------------------------------------

def print_summary(summary: pd.DataFrame) -> None:
    """Print the model comparison table."""

    print("\n" + "=" * 100)
    print("MODEL PERFORMANCE SUMMARY")
    print("=" * 100)

    print(
        summary.to_string(index=False)
    )

    print("\n" + "=" * 100)
    print("FASTEST MODEL")
    print("=" * 100)

    fastest = summary.loc[
        summary["avg_latency_ms"].idxmin()
    ]

    print(
        f"{fastest['model']} "
        f"({fastest['avg_latency_ms']:.2f} ms average latency)"
    )

    print("\n" + "=" * 100)
    print("LOWEST AVERAGE MEMORY USAGE")
    print("=" * 100)

    lowest_memory = summary.loc[
        summary["avg_memory_peak_pct"].idxmin()
    ]

    print(
        f"{lowest_memory['model']} "
        f"({lowest_memory['avg_memory_peak_pct']:.2f}% peak memory)"
    )

    print("\n" + "=" * 100)
    print("HIGHEST RETRIEVAL RECALL")
    print("=" * 100)

    highest_recall = summary.loc[
        summary["avg_retrieval_recall"].idxmax()
    ]

    print(
        f"{highest_recall['model']} "
        f"({highest_recall['avg_retrieval_recall']:.2f} recall)"
    )

    print("\n" + "=" * 100)
    print("BLANK RESPONSES")
    print("=" * 100)

    for _, row in summary.iterrows():
        print(
            f"{row['model']}: "
            f"{int(row['blank_answers'])} blank responses"
        )


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main() -> None:
    """Run the complete analysis."""

    print("Loading evaluation results...")

    df = load_results(INPUT_FILE)

    print(
        f"Loaded {len(df)} evaluation results "
        f"from {df['model'].nunique()} models."
    )

    df = prepare_data(df)

    summary = create_model_summary(df)

    summary.to_csv(
        OUTPUT_FILE,
        index=False,
    )

    print_summary(summary)

    print("\n" + "=" * 100)
    print(f"Analysis saved to: {OUTPUT_FILE}")
    print("=" * 100)


if __name__ == "__main__":
    main()